#!/usr/bin/env python3
"""Bundle the ES-module sources into one classic script, app.bundle.js.

Safari could leave the module graph half-loaded behind an old service worker
(a black screen with no error), so the page now loads a single plain script.
Edit content.js / config.js / sync.js / app.js as before, then run:
    python3 together/build.py
It also syntax-checks the result and stamps index.html with a content hash.
Then run the tests: node together/tests/run.mjs
"""
import pathlib, re

HERE = pathlib.Path(__file__).parent
EXPORT = re.compile(r'^export\s+(?:async\s+)?(?:const|let|function)\s+([A-Za-z_$][\w$]*)', re.M)
IMPORT = re.compile(r'^import .*$\n', re.M)

def src(name):
    return IMPORT.sub('', (HERE / name).read_text())

def namespace(var, name):
    body = src(name)
    names = EXPORT.findall(body)
    body = re.sub(r'^export\s+', '', body, flags=re.M)
    # getters keep live bindings working (S.status changes over time)
    getters = ', '.join(f'get {n}() {{ return {n} }}' for n in names)
    return f'const {var} = (() => {{\n{body}\nreturn {{ {getters} }}\n}})()\n'

out = ["// GENERATED by build.py from config.js, content.js, sync.js, app.js. Do not edit.",
       "(() => {", "'use strict'",
       re.sub(r'^export\s+', '', src('config.js'), flags=re.M),
       namespace('C', 'content.js'),
       namespace('S', 'sync.js'),
       src('app.js'),
       "window.tgStarted = true",
       "})()"]
bundle = '\n'.join(out)
(HERE / 'app.bundle.js').write_text(bundle)

# Syntax-check the bundle when node is around, so a broken build never ships.
import shutil, subprocess, sys, hashlib
if shutil.which('node'):
    chk = subprocess.run(['node', '--check', str(HERE / 'app.bundle.js')], capture_output=True, text=True)
    if chk.returncode:
        sys.exit('app.bundle.js has a syntax error:\n' + chk.stderr)

# Stamp index.html with a content hash, so phones can never mix an old file
# with a new one (this used to be a manual ?v= bump, and forgetting it caused
# the black-screen bug).
ver = hashlib.sha1((bundle + (HERE / 'app.css').read_text()).encode()).hexdigest()[:10]
idx = HERE / 'index.html'
html = re.sub(r'(app\.(?:bundle\.js|css))\?v=[0-9a-z]+', lambda m: m.group(1) + '?v=' + ver, idx.read_text())
idx.write_text(html)
print('wrote app.bundle.js, stamped index.html v=' + ver)
