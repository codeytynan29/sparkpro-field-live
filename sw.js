// '/sparkpro-field-live/sw.js' → '/sparkpro-field-live/'
const BASE = self.location.pathname.replace(/sw\.js$/, '')

// Pull the shell and every hashed asset down on install, so the app opens
// offline even if its FIRST open is offline. Cached one-by-one on purpose:
// cache.addAll() rejects the whole batch if any single request fails, which
// would leave a tester with no cache at all because of one stale entry.
//
// Deliberately does NOT skipWaiting() any more. It used to, which sounded like
// "apply updates promptly" and was actually a way to break the app underneath
// someone: the new worker activated immediately, the activate step below
// deleted the shell cache the RUNNING page was still being served from, and
// that page — still executing the previous build's JavaScript — could then ask
// for a hashed chunk that no longer existed in the cache or on the server.
//
// So a new build now installs quietly and waits. The page in front of the tech
// keeps its own assets, intact, until they choose the moment to take the
// update (see lib/appUpdate.js, which surfaces the waiting worker as a banner
// and posts the message below when it is tapped).
self.addEventListener('install', event => {
  event.waitUntil(
    caches.open(CACHE)
      .then(c => Promise.all(
        PRECACHE.map(url => c.add(url).catch(() => {}))
      ))
      .catch(() => { /* a partial precache still beats refusing to install */ })
  )
})

// The tech tapped "Update". Stand down the waiting period, activate, and take
// over — the page reloads itself once it sees the controller change.
self.addEventListener('message', event => {
  if (event.data?.type === 'SKIP_WAITING') self.skipWaiting()
})

// Evict the SHELL caches this worker replaces — and nothing else.
//
// This used to delete every cache that was not the current one, which read as
// obviously correct and was catastrophic: the voice pack lives in a cache of
// its own (`sparkpro-voice-pro`, around 286 MB the tech chose to download over
// wifi), and the shell cache name is a hash of the asset list, so it changes on
// EVERY deploy. Each deploy therefore threw away the voice pack, and the next
// launch asked them to download it again — on cellular, in the field.
//
// It also destroyed exactly the thing the pack exists for. A tech who
// downloaded it deliberately so Spark would work with no signal would find it
// gone the first time they opened the app after any update.
//
// So the predicate is now explicit about what it owns. Anything that is not a
// SparkPro Field shell cache is somebody else's and is left alone; the app
// manages the voice packs itself and offers a Remove control for them.
const SHELL_PREFIX = 'sparkpro-field-'

self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(
        keys
          .filter(k => k.startsWith(SHELL_PREFIX) && k !== CACHE)
          .map(k => caches.delete(k))
      ))
      .then(() => self.clients.claim())
  )
})

self.addEventListener('fetch', event => {
  const req = event.request
  if (req.method !== 'GET') return

  const url = new URL(req.url)

  // Cross-origin (Supabase, Google, model-lookup links) always goes to network.
  // Never serve a cached auth response.
  if (url.origin !== self.location.origin) return

  // Page loads: try network so a deployed update is picked up, but fall back to
  // the cached shell so the app still opens with no signal.
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then(res => {
          const copy = res.clone()
          caches.open(CACHE).then(c => c.put(req, copy)).catch(() => {})
          return res
        })
        .catch(() => caches.match(req).then(hit => hit || caches.match(BASE + 'index.html')))
    )
    return
  }

  // Static assets are content-hashed by Vite, so a cache hit is always correct
  // for that exact filename — cache-first is safe and makes cold opens instant.
  event.respondWith(
    caches.match(req).then(hit => {
      if (hit) return hit
      return fetch(req).then(res => {
        if (res.ok && res.type === 'basic') {
          const copy = res.clone()
          caches.open(CACHE).then(c => c.put(req, copy)).catch(() => {})
        }
        return res
      })
    })
  )
})
